#!/usr/bin/env python3
"""Split Galmuri11 (regular + bold) into a common part and a rare part, and write css/fonts.css.

common: everything in the font except Hangul syllables, plus the 2,350 everyday syllables of
        KS X 1001 — what nearly every page uses.
rare:   the other 8,822 Hangul syllables, loaded only when a page shows one (unicode-range).

Needs fonttools + brotli:  pip install fonttools brotli
Run from the repo root with the full fonts in tools/fonts-src/ (Galmuri11.woff2, Galmuri11-Bold.woff2):
    python3 tools/split-fonts.py
"""
import subprocess, tempfile, os
from fontTools.ttLib import TTFont

SRC = 'tools/fonts-src'
common = set()
for b1 in range(0xB0, 0xC9):
    for b2 in range(0xA1, 0xFF):
        try:
            ch = bytes([b1, b2]).decode('euc-kr')
        except UnicodeDecodeError:
            continue
        if 0xAC00 <= ord(ch) <= 0xD7A3:
            common.add(ord(ch))
rare = sorted(set(range(0xAC00, 0xD7A4)) - common)

def runs(xs):
    out, s, p = [], None, None
    for x in xs:
        if s is None: s = p = x
        elif x == p + 1: p = x
        else: out.append((s, p)); s = p = x
    out.append((s, p))
    return out
rng = ', '.join(('U+%X' % a) if a == b else ('U+%X-%X' % (a, b)) for a, b in runs(rare))

with tempfile.TemporaryDirectory() as tmp:
    for name in ['Galmuri11', 'Galmuri11-Bold']:
        src = f'{SRC}/{name}.woff2'
        cmap = TTFont(src).getBestCmap()
        keep = sorted(c for c in cmap if not (0xAC00 <= c <= 0xD7A3)) + sorted(common)
        for part, cps in [('common', keep), ('rare', rare)]:
            lst = os.path.join(tmp, f'{name}-{part}.txt')
            open(lst, 'w').write(','.join('U+%04X' % c for c in cps))
            subprocess.run(['pyftsubset', src, f'--unicodes-file={lst}', '--flavor=woff2', '--layout-features=*',
                            '--name-IDs=*', '--notdef-outline', f'--output-file=fonts/{name}-{part}.woff2'], check=True)

css = f'''/* Galmuri11 split in two (generated by tools/split-fonts.py — do not edit by hand).
   *-common: Latin, symbols and the 2,350 everyday Hangul syllables (KS X 1001) — always loaded.
   *-rare:   the other 8,822 Hangul syllables — downloaded only when a page shows one of them.
   The rare faces come LAST so they win for their own syllables; unicode-range keeps them
   from loading otherwise. */
@font-face {{ font-family: "Galmuri11"; src: url("../fonts/Galmuri11-common.woff2") format("woff2"); font-weight: 400; font-display: swap; }}
@font-face {{ font-family: "Galmuri11"; src: url("../fonts/Galmuri11-Bold-common.woff2") format("woff2"); font-weight: 700; font-display: swap; }}
@font-face {{ font-family: "Galmuri11"; src: url("../fonts/Galmuri11-rare.woff2") format("woff2"); font-weight: 400; font-display: swap;
  unicode-range: {rng}; }}
@font-face {{ font-family: "Galmuri11"; src: url("../fonts/Galmuri11-Bold-rare.woff2") format("woff2"); font-weight: 700; font-display: swap;
  unicode-range: {rng}; }}
@font-face {{ font-family: "NeoDGM"; src: url("../fonts/NeoDGM.woff2") format("woff2"); font-display: swap; }}
'''
open('css/fonts.css', 'w').write(css)
print('fonts split; css/fonts.css written')
