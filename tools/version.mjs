#!/usr/bin/env node
// Stamp every CSS / JS file in index.html with a content hash (?v=…), so that after a deploy
// browsers fetch exactly the files that changed and never mix old and new modules.
//
//   node tools/version.mjs           rewrite the block between <!-- assets:start --> and <!-- assets:end -->
//   node tools/version.mjs --check   exit 1 if index.html is out of date (used by `npm test`)
//
// Modules import each other with plain relative paths ('./ui.js'); the import map below sends
// each of those to its versioned URL. No build step, nothing else to change.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
const hash = (p) => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex').slice(0, 8);
const v = (p) => `${p}?v=${hash(path.join(ROOT, p))}`;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(d =>
    d.isDirectory() ? (d.name === 'vendor' ? [] : walk(path.join(dir, d.name)))
      : d.name.endsWith('.js') ? [path.join(dir, d.name)] : []);
}
const modules = walk(path.join(ROOT, 'js')).map(rel).filter(p => p !== 'js/index.js' && p !== 'js/config.example.js').sort();
const styles = ['css/fonts.css', 'css/base.css', 'css/extras.css'];

const imports = Object.fromEntries(modules.map(p => [`./${p}`, `./${v(p)}`]));
const block = [
  '<!-- assets:start (generated by tools/version.mjs — run it before committing) -->',
  ...styles.map(p => `  <link rel="stylesheet" href="${v(p)}">`),
  '  <script defer src="js/vendor/supabase-js-2.117.3.umd.js"></script>',
  '  <script type="importmap">',
  `  ${JSON.stringify({ imports }, null, 2).split('\n').join('\n  ')}`,
  '  </script>',
  `  <script type="module" src="${v('js/index.js')}"></script>`,
  '  <!-- fetch every module at once instead of one import level at a time -->',
  ...modules.map(p => `  <link rel="modulepreload" href="${v(p)}">`),
  '  <!-- assets:end -->',
].join('\n');

const file = path.join(ROOT, 'index.html');
const html = fs.readFileSync(file, 'utf8');
const re = /<!-- assets:start[\s\S]*?<!-- assets:end -->/;
if (!re.test(html)) { console.error('index.html: no <!-- assets:start --> … <!-- assets:end --> block'); process.exit(2); }
const next = html.replace(re, block);
if (process.argv.includes('--check')) {
  if (next !== html) { console.error('index.html is out of date: run  node tools/version.mjs'); process.exit(1); }
  console.log('index.html versions are up to date');
} else {
  fs.writeFileSync(file, next);
  console.log(next === html ? 'index.html already up to date' : `index.html updated (${modules.length + 1} modules, ${styles.length} stylesheets)`);
}
